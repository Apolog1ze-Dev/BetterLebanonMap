const LANGS = ["ar", "fr", "en"];
let current = "fr";
try {
  const saved = localStorage.getItem("blm-lang");
  if (LANGS.includes(saved)) current = saved;
} catch { /* storage unavailable */ }

export const lang = () => current;
export const langIndex = () => ({ ar: 0, fr: 1, en: 2 })[current];

export function setLang(l) {
  current = LANGS.includes(l) ? l : "fr";
  try { localStorage.setItem("blm-lang", current); } catch { /* ignore */ }
  document.documentElement.lang = current;
  document.documentElement.dir = current === "ar" ? "rtl" : "ltr";
}

export function t(key, vars = {}) {
  const s = STR[current][key] ?? STR.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}

// Pick a name in the current language from {ar, fr, en} or [ar, fr, en].
export function pick(names) {
  if (!names) return "";
  if (Array.isArray(names)) return names[langIndex()] ?? names[1] ?? names[0];
  return names[current] ?? names.fr ?? names.ar;
}

const fmt = { ar: new Intl.NumberFormat("ar-LB"), fr: new Intl.NumberFormat("fr-FR"), en: new Intl.NumberFormat("en-US") };
export const num = n => fmt[current].format(n);

export function distance(m) {
  return m < 950 ? `${Math.round(m / 10) * 10 || Math.round(m)} ${t("m")}` : `${(m / 1000).toFixed(m < 9500 ? 1 : 0)} ${t("km")}`;
}

export function duration(s) {
  const min = Math.max(1, Math.round(s / 60));
  return min < 60 ? `${min} ${t("min")}` : `${Math.floor(min / 60)} ${t("h")} ${String(min % 60).padStart(2, "0")}`;
}
